#   新兴市场       4      4      100%       100%          保留
#   日经          2      2      100%       100%          保留
#   日本          2      2      100%       100%          保留
#   越南          2      2      100%       100%          保留
#   印度          2      1       50.0%      100%          保留
#   德国          2      2      100%       100%          保留
#   法国          2      2      100%       100%          保留
#   东南亚        2      2      100%       100%          保留
#   欧洲          2      2      100%       100%          保留
#   道琼          5      1       20.0%       80%          保留（4 只非QDII名中 3 只真QDII）
#   标普         30      8       26.7%       46.7%        保留 + 否定词 → 87.5%
