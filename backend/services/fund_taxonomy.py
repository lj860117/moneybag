# ============================================================
#
# 判据（v9.9.36）：**名称含 "QDII" OR 命中高精关键词白名单（带否定词）**
#
# ------------------------------------------------------------------
# 一、为什么必须回到名称（结构化字段这条路实测走不通）
# ------------------------------------------------------------------
# 修前这里写的是 filter_type(["QDII"])，同样是拿 fund_type 去匹配 ——
# fund_type 全量取值只有 6 个（混合型 6417 / 股票型 6280 / 债券型 4758 /
# 货币型 335 / REITs 104 / 其他 55），**没有 QDII** → ranks.qdii 也恒为空。
# 与 index 完全同一个病。已核对归档 data/fund_rank_ts_20260910.json：
# index=0、qdii=0，属长期静默为空，不是新回归。
#
# ⚠️ 为什么这里**没有**可替代的结构化字段（与 index 的关键差异）：
#   * invest_type 全量 36 个取值里**没有任何一个含 QDII**（实测命中 0 只）；
#   * fund_type 也没有（实测命中 0 只）。
#   所以 index 那套"改用 invest_type"的办法，在 QDII 上**不存在**。
# AKShare 侧（选基页数据源）同样没有 invest_type / fund_type / 类型列，
# 也只能走名称。
#
# ------------------------------------------------------------------
# 二、为什么用纯子串 "QDII" 而不是 "(QDII"
# ------------------------------------------------------------------
#   纯子串能一并覆盖 "(QDII-LOF)" / "(QDII-FOF)" 这类复合后缀；AKShare 侧
#   实测纯子串 355 vs "(QDII)" 半角 324，多出来的就是复合后缀。
#
# ------------------------------------------------------------------
# 三、为什么"纯名称含 QDII"不够 —— 必须再并上关键词
# ------------------------------------------------------------------
# AKShare 的「基金简称」会**截断**法定名称里的 "(QDII)" 后缀。用雪球
# `fund_individual_basic_info_xq` 的「基金类型」做真值核对（2026-09-14，
# 全市场 20357 只），候选池里有 **24 只真 QDII 的简称不含 QDII**，例如：
#     160213 国泰纳斯达克100指数        （基金类型=QDII-股票）
#     519981 长信标普100等权重指数人民币 （基金类型=QDII-股票）
#     050015 博时大中华亚太精选          （基金类型=QDII-股票）
#     160140 南方道琼斯美国精选A         （基金类型=QDII-房地产信托）
# 纯名称口径在 score top30 / 1y top50 两个视角上分别漏判 3 只 / 4 只。
#
# ------------------------------------------------------------------
# 四、24 个关键词的逐个实测精度（AKShare 全市场 20357 只，2026-09-14）
# ------------------------------------------------------------------
# 真值 = 雪球「基金类型」以 QDII 开头（**不是**"名称含 QDII"代理标签 ——
# 代理标签会把上面那批截断简称的真 QDII 算成误判，从而低估精度）。
# 反向校验：名称含 QDII 且真值非 QDII = **0 只**，标记本身无假阳性。
#
#   关键词      命中   含QDII名  代理精度   **真值精度**   处置
