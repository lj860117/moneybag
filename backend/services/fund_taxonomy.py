# 这类**投 A 股 / 港股通**的境内基金。加否定词 {港股通, 中国A股, 香港上市中国}
# 可拦掉其中 12 只，精度 46.7% → 87.5%。
# ⚠️ 在 top-N（score top30 / 1y top50）上**不加否定词也已经是 0 误判**，
# 因为那 5 只在池内的真非 QDII 标普基金 score 最高只有 2.38，够不上门槛。
# 加否定词是为了全市场层面的口径干净，**不是** top-N 的必要条件 —— 别以为
# 它是冗余就删掉，也别以为删了它 top-N 会红。
#
# ------------------------------------------------------------------
# 六、本判据的实测净效果（候选池 7945 只，同一快照同一真值）
# ------------------------------------------------------------------
#   判据                              池内命中  score30 误判/漏判  1y50 误判/漏判
#   24 词并集（修前 fund_screen.py）      338      6 / 0              7 / 0
#   纯名称含 QDII                        158      0 / 3              0 / 4
#   **本判据（14 词 union）**             175      **0 / 0**          **0 / 0**
#
# 两个视角都严格优于修前现状与纯名称口径。
QDII_NAME_MARKER = "QDII"

# 高精关键词白名单（14 个）。每个词的实测精度见上方表格；加词必须有实测数字。
QDII_NAME_KEYWORDS: tuple = (
    "纳斯达克", "海外", "亚太", "新兴市场", "日经", "日本", "越南", "印度",
    "德国", "法国", "欧洲", "东南亚", "道琼", "标普",
)

# 关键词的否定词：命中关键词但如果同时命中否定词，则该关键词不作数。
# 目前只有"标普"需要 —— 它既出现在真 QDII（标普500/标普美国消费/标普全球石油）
# 也出现在境内基金（标普中国A股红利机会 / 标普港股通低波红利）里。
QDII_KEYWORD_NEGATIONS: dict = {
    "标普": ("港股通", "中国A股", "香港上市中国"),
}

# 被**删掉**的词（留档用，供回归守卫断言"不许加回来"）。
# 想加回任意一个，请先补它的全市场真值精度，否则一律拒绝。
QDII_REJECTED_KEYWORDS: tuple = (
    "全球", "恒生", "港股", "国际", "纳指", "美股", "英国", "韩国", "S&P",
)


def is_qdii_fund(item: dict) -> bool:
    """QDII 基金判定：法定名称标记 OR 高精关键词白名单（带否定词）

    判据 = ``QDII_NAME_MARKER in name`` **OR** 命中 ``QDII_NAME_KEYWORDS``
    中的任一词且未被 ``QDII_KEYWORD_NEGATIONS`` 中对应的否定词排除。

    为什么要并上关键词：AKShare / 雪球等数据源的「基金简称」会截断法定名称
    里的 "(QDII)" 后缀，实测候选池里有 24 只真 QDII 的简称不含 QDII（如
    国泰纳斯达克100指数、长信标普100等权重指数人民币）。只认标记会漏判。
    每个保留词的实测精度见 QDII_NAME_MARKER 上方的表格。

    Args:
        item: 至少带 name 字段的一条记录（fund_rank_build 的 ranks_all 项、
              fund_screen 的候选行均可）。name 允许为 None / 非字符串。

    Returns:
        True 表示这是一只 QDII 基金。name 缺失或为 None 时返回 False。
    """
    name = item.get("name") or ""
    if not isinstance(name, str):
        name = str(name)
    if QDII_NAME_MARKER in name:
        return True
    for keyword in QDII_NAME_KEYWORDS:
        if keyword in name:
            # 否定词命中 → 这个词是"标普中国A股"这类境内用法，不作数
            if any(neg in name for neg in
                   QDII_KEYWORD_NEGATIONS.get(keyword, ())):
                continue
            return True
    return False
