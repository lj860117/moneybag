# **删词的三个核心理由**（后人想加回来请先读这段）：
#   * 港股 440 命中精度 ≈0：全是"港股通/港股通ETF"，走的是互联互通额度，
#     法律上**不是** QDII。这是 24 词口径 554 只误判里最大的一块。
#   * 恒生 230 命中里，抽样 19 只有 17 只是误判，其中大头是**"恒生前海"
#     基金公司名**（恒生前海高端制造A / 消费升级 / 恒裕债券A）—— "恒生"
